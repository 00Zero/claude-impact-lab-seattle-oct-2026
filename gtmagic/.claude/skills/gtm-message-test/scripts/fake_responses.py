#!/usr/bin/env python3
"""FAKE customer responses, for testing evaluate.py before the simulation skill exists.

Usage: python3 fake_responses.py <intake.json> <positioning-set.json> <experiment-request.json> [--n 48] [--seed 7] [--out FILE]

Not a simulation: scores are made up. Customers are spread evenly across segments (CONTRACTS.md's
"balanced" default); each one leans toward options that target its segment, and dislikes the decoy.
The output follows CONTRACTS.md → CustomerResponses and is marked FAKE so evaluate.py says so.
"""
from __future__ import annotations

import argparse
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # works under python -I too
from ordering import ordering_index  # noqa: E402

DIMENSIONS = ("relevance", "credibility", "differentiation", "clarity", "actionIntent")
OBJECTIONS = ["Sounds like every other app.", "Not sure it's worth the price.", "I'd need to see how it works first.",
              "Doesn't sound like it's for someone like me."]


def fake(intake: dict, positioning: dict, request: dict, n: int, seed: int) -> dict:
    rng = random.Random(seed)
    seg_ids = [s["id"] for s in intake.get("segments", [])]
    by_id = {h["id"]: h for h in positioning.get("hypotheses", [])}
    labels = {s["label"]: s["candidateId"] for s in request["stimuli"]}
    orderings = request["orderings"]
    customers = [(f"cust_r1_{i + 1}", seg_ids[i % len(seg_ids)]) for i in range(n)]
    ids = {c for c, _ in customers}
    repeat_ids = set(request.get("repeatCustomerIds") or []) & ids or {c for c, _ in customers[:10]}
    responses: list[dict] = []

    def answer(cust: str, seg: str, k: int, is_repeat: bool) -> dict:
        ratings, best, best_intent = [], "none", 3.4  # below this, the customer picks "none"
        order = list(reversed(orderings[k])) if is_repeat else orderings[k]
        for label in order:
            cid = labels[label]
            h = by_id[cid]
            base = {"decoy": 1.6, "founder-current": 3.0}.get(h.get("source"), 2.8)
            base += 0.9 if seg in h.get("targetSegmentIds", []) else 0
            scores = {d: max(1, min(5, round(base + rng.gauss(0, 0.8)))) for d in DIMENSIONS}
            ratings.append({"candidateId": cid, "scores": scores})
            if scores["actionIntent"] + rng.random() * 0.5 > best_intent:
                best, best_intent = cid, scores["actionIntent"] + rng.random() * 0.5
        objections = [{"candidateId": r["candidateId"], "text": rng.choice(OBJECTIONS)} for r in ratings if r["scores"]["actionIntent"] <= 2][:2]
        return {"id": f"resp_{len(responses) + 1}", "experimentId": request["id"], "customerId": cust, "segmentId": seg,
                "orderingIndex": k, "isRepeat": is_repeat, "status": "answered", "choice": best, "ratings": ratings,
                "objections": objections, "reasoning": "FAKE", "model": "fake", "promptVersion": "fake-v1"}

    position = {s: 0 for s in seg_ids}
    present = [s for s in seg_ids if any(seg == s for _, seg in customers)]  # segments with nobody in the sample don't count
    for cust, seg in customers:
        k = ordering_index(present.index(seg), len(present), position[seg], len(orderings))
        position[seg] += 1
        responses.append(answer(cust, seg, k, False))
        if cust in repeat_ids:  # asked again with the same ordering reversed
            responses.append(answer(cust, seg, k, True))
    return {"_note": "FAKE: generated by fake_responses.py for testing. Not a simulation.",
            "experimentId": request["id"], "requestFingerprint": request.get("fingerprint"), "responses": responses}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("intake")
    ap.add_argument("positioning")
    ap.add_argument("request")
    ap.add_argument("--n", type=int, default=48)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out", default="customer-responses.fake.json")
    args = ap.parse_args()
    if args.n < 1:
        print("ERROR --n must be at least 1")
        return 1
    loaded = []
    for path in (args.intake, args.positioning, args.request):
        with open(path, encoding="utf-8") as f:
            loaded.append(json.load(f))
    data = fake(*loaded, args.n, args.seed)
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    print(f"OK wrote {len(data['responses'])} FAKE responses to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
