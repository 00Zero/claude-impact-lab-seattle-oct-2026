import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { writeFakeArms } from "./fake";
import { prep } from "./prep";
import { report } from "./score";
import { BENCH_DIR, SPLITS, type Split } from "./types";

const USAGE = `Twin-2K-500 Mega-Study "infotainment" benchmark (ICP-conditioned message preference; data only, no model calls here)

  python3 scripts/prep_megastudy.py         download + flatten raw data into data/megastudy/ (needs pandas + pyarrow)
  npm run megastudy -- prep                 splits, segment table, truth files, blind batches, published reference arms
  npm run megastudy -- fake                 write sanity arms (oracle, random, train-mean) generated by code
  npm run megastudy -- report [--split val|test] [--arms a,b]   print scores; writes benchmarks/megastudy/RESULTS.md`;

const asSplit = (s: string | undefined): Split => {
  if (s && (SPLITS as readonly string[]).includes(s)) return s as Split;
  throw new Error("--split must be train, val or test");
};

function main(): void {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: { split: { type: "string" }, arms: { type: "string" } },
  });
  switch (positionals[0]) {
    case "prep":
      return prep();
    case "fake":
      return writeFakeArms();
    case "report": {
      const splits: Split[] = values.split ? [asSplit(values.split)] : ["val", "test"];
      const arms = values.arms?.split(",").map((a) => a.trim()).filter(Boolean);
      const md = [
        "# Infotainment benchmark: results",
        "",
        "Twin-2K-500 Mega-Study `infotainment` (300 US adults rated 18 news-post cards, 1–7 likelihood to share). See README.md for metric definitions. `ref-*` rows are published Mega-Study twin predictions (reference only); `oracle-*`, `random-*` and `null-*` are code-generated sanity arms.",
        "",
        ...splits.map((s) => report(s, arms)),
      ].join("\n");
      if (!arms) writeFileSync(join(BENCH_DIR, "RESULTS.md"), `${md}\n`);
      console.log(md);
      return;
    }
    default:
      console.log(USAGE);
  }
}

try {
  main();
} catch (err) {
  console.error(`error: ${(err as Error).message}`);
  process.exitCode = 1;
}
